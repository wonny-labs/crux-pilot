// No C build needs Node.js: nothing in a CMake, Kconfig or Zephyr file names the web tools.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';
import { nodeUseIn } from '../c-boundary.ts';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');

function tracked(...pathspecs: string[]): string[] {
  return execFileSync('git', ['ls-files', '--', ...pathspecs], { cwd: repo, encoding: 'utf8' })
    .split('\n')
    .filter((line) => line !== '');
}

for (const [name, text] of Object.entries({
  'find_program for node': 'find_program(NODE_EXECUTABLE node REQUIRED)',
  'find_program across lines': 'find_program(\n  NODE_EXECUTABLE\n  NAMES node nodejs\n  REQUIRED\n)',
  'a custom target using the found program': 'add_custom_target(web ALL COMMAND ${NODE_EXECUTABLE} tools/build.ts)',
  'a custom command running node': 'add_custom_command(OUTPUT x COMMAND node tools/build.ts)',
  'node by path': 'add_custom_command(OUTPUT x COMMAND /usr/bin/node build.js)',
  npm: 'execute_process(COMMAND npm ci)',
  npx: 'execute_process(COMMAND npx esbuild)',
  yarn: 'execute_process(COMMAND yarn build)',
  pnpm: 'execute_process(COMMAND pnpm build)',
  'find_package for node': 'find_package(Nodejs REQUIRED)',
  'the web tools by path': 'add_subdirectory(web/mock)',
  'the Preact example by path': 'add_subdirectory(samples/web/preact)',
  'the Angular sample by path': 'add_subdirectory(samples/web/angular)',
  'the web tools beside the root of the source tree': 'COMMAND python3 ${CMAKE_CURRENT_LIST_DIR}/../web/tools/gen-types.ts',
  'the API directory': 'add_subdirectory(web/api)',
  'the Node.js lint tools of the API specification': 'add_subdirectory(web/api/lint)',
  'a file beside the specification': 'COMMAND check ${PROJECT_SOURCE_DIR}/web/api/examples.json',
  'a copy of the specification under another name': 'COMMAND check ${PROJECT_SOURCE_DIR}/web/api/openapi.yaml.orig',
  'the lint tools named after the specification': '/* web/api/openapi.yaml, linted by web/api/lint */',
  'a frontend directory under a component path': 'COMMAND python3 components/web/../../web/tools/gen-types.ts',
  'the specification as a directory, then the lint tools': 'COMMAND check web/api/openapi.yaml/../lint',
  'the lint package beside the specification path': 'COMMAND check web/api/openapi.yaml/../lint/package.json',
  'the specification name with a trailing slash': 'COMMAND check web/api/openapi.yaml/',
  'web tools under a directory that only ends in components': 'COMMAND python3 mycomponents/web/tools/gen-types.ts',
  'web tools under a directory that starts with an x before components': 'COMMAND python3 xcomponents/web/tools/gen-types.ts',
  'the API lint under a directory that ends in components': 'add_subdirectory(mycomponents/web/api/lint)',
  'a hidden directory that ends in components': 'COMMAND python3 .components/web/tools/gen-types.ts',
  'an npm tool run on the specification': 'COMMAND npx spectral lint web/api/openapi.yaml',
})) {
  test(`${name} counts as a C build using Node.js`, () => {
    assert.notDeepEqual(nodeUseIn(text), [], text);
  });
}

for (const text of [
  'A device tree node holds the settings.',
  'DT_NODELABEL(flexspi)',
  'zephyr_library_sources(src/node.c)',
  'config CRUX_WEB\n  bool "Web service"',
  'add_subdirectory(components/web)',
  // The firmware component that generates the route table is not the frontend directory.
  'COMMAND python3 ${CMAKE_CURRENT_LIST_DIR}/../components/web/tools/web_routes.py',
  '/* Generated by components/web/tools/web_routes.py. Do not edit. */',
  // The OpenAPI specification is a plain YAML file that firmware code and tests may name.
  'add_test(NAME x COMMAND python3 check.py --spec ${PROJECT_SOURCE_DIR}/web/api/openapi.yaml)',
  '/* The JSON forms of web/api/openapi.yaml. */',
  '/* Written as the StatusReport of web/api/openapi.yaml. */',
  // A component directory is met as `components/`, `../components/` or `${DIR}/components/`, so any path
  // segment named exactly `components` is the firmware tree. A scan cannot tell `src/components/` from
  // `${DIR}/components/`, and no nested components directory exists.
  'COMMAND python3 src/components/web/tools/web_routes.py',
  // Known gap, accepted with the rule on the specification file: a Node.js tool run on the specification
  // by its bare path is not caught by the path rule. The npm and npx rules still catch `npx spectral`.
  'COMMAND redocly lint web/api/openapi.yaml',
  'COMMAND spectral lint web/api/openapi.yaml',
]) {
  test(`${JSON.stringify(text)} does not count`, () => {
    assert.deepEqual(nodeUseIn(text), []);
  });
}

test('no C build definition names Node.js, npm or the web tools', () => {
  const files = tracked(
    ':(glob)**/CMakeLists.txt',
    ':(glob)**/*.cmake',
    ':(glob)**/Kconfig*',
    ':(glob)**/*.conf',
    ':(glob)**/module.yml',
    'west.yml',
    'CMakePresets.json',
  );
  assert.ok(files.length > 10, 'the file list must not be empty');
  const found = files.flatMap((file) => nodeUseIn(readFileSync(join(repo, file), 'utf8')).map((use) => `${file}: ${use}`));
  assert.deepEqual(found, []);
});

test('no component names the web tools', () => {
  const found = tracked(':(glob)components/**').flatMap((file) =>
    nodeUseIn(readFileSync(join(repo, file), 'latin1')).map((use) => `${file}: ${use}`),
  );
  assert.deepEqual(found, []);
});

test('the frontend adds nothing under components', () => {
  assert.deepEqual(tracked(':(glob)components/**/*.ts', ':(glob)components/**/*.tsx', ':(glob)components/**/package.json'), []);
});
