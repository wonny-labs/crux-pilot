"""The one form of the C source that web_assets.py writes, shared by the writer and the route tool.

web_assets.py writes the source with render_source(). web_routes.py accepts a source as a packaged web
folder only if check_source() finds it byte for byte equal to what render_source() makes from the
facts in it: the content policy choice, each asset's path and its embedded bytes. Everything else in
the file, which is every line that names a handler, a table, a header, a route or a preprocessor
directive, is derived and never read, so no other text can be accepted, however it is written.

The facts are read loosely on purpose, and then thrown away by the comparison: a file that the loose
read misunderstands cannot equal what is rendered from that reading, and is refused.
"""
import re

SECURITY_HEADER_COUNT = 3
CACHE_REVALIDATE = "no-cache"
CACHE_IMMUTABLE = "max-age=31536000, immutable"
GENERATED = "/* Generated by components/web/tools/web_assets.py. Do not edit. */"
PATH_MAX = 128
# One path segment: what the server compares without decoding.
SEGMENT = r"[A-Za-z0-9._~-]+"

TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json",
    ".webmanifest": "application/manifest+json",
    ".txt": "text/plain; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".gif": "image/gif",
    ".webp": "image/webp",
    ".avif": "image/avif",
    ".ico": "image/vnd.microsoft.icon",
    ".woff": "font/woff",
    ".woff2": "font/woff2",
}
# A hash in a file name, set off by - or ., with a digit or a capital in it so that a word does not
# count: the token after the last separator only, so a hash that holds a hyphen stays revalidated.
FINGERPRINT = re.compile(r"[-.]([A-Za-z0-9_]{8,32})\.[A-Za-z0-9]+\Z")
GZIP_MAGIC = b"\x1f\x8b"

_PATH = re.compile(r"/(?:" + SEGMENT + r"(?:/" + SEGMENT + r")*)?\Z")
_STYLE = re.compile(r"^#define CRUX_ASSETS_INLINE_STYLES ([01])$", re.MULTILINE)
_ASSET = re.compile(
    r"^/\* (/[A-Za-z0-9._~/-]*), served as (?:gzip|identity) \*/\n"
    r"static const uint8_t crux_web_asset_data_\d{4}\[\] = \{\n"
    r"((?:    0x[0-9a-f]{2}(?:, 0x[0-9a-f]{2})*,\n)+)\};\n", re.MULTILINE)
_BYTE = re.compile(r"0x([0-9a-f]{2})")


class FormError(Exception):
    """A source that is not what web_assets.py writes."""


def fingerprinted(name):
    """Whether a file name holds a content hash, so its content cannot change under that name."""
    match = FINGERPRINT.search(name)
    if match is None:
        return False
    token = match.group(1)
    return any(character.isdigit() or character.isupper() for character in token)


def content_type(path):
    return TYPES[path[path.rfind("."):].lower()] if "." in path.rsplit("/", 1)[-1] else None


def cache_value(path):
    return CACHE_IMMUTABLE if fingerprinted(path.rsplit("/", 1)[-1]) else CACHE_REVALIDATE


def _data_rows(data):
    return "\n".join("    " + ", ".join(f"0x{byte:02x}" for byte in data[start:start + 16]) + ","
                     for start in range(0, len(data), 16))


def render_source(style, assets):
    """The source for a style, 'strict' or 'inline', and (path, embedded bytes) pairs in path order.

    Returns the text and the number of routes. The type, encoding, cache class, header counts, table,
    count and routes are all derived from the paths and bytes.
    """
    lines = [GENERATED, f"#define CRUX_ASSETS_INLINE_STYLES {1 if style == 'inline' else 0}",
             '#include "web_assets_internal.h"', ""]
    gzip_flags = []
    for index, (path, data) in enumerate(assets):
        gzip = data[:2] == GZIP_MAGIC
        gzip_flags.append(gzip)
        lines.append(f"/* {path}, served as {'gzip' if gzip else 'identity'} */")
        lines.append(f"static const uint8_t crux_web_asset_data_{index:04d}[] = {{")
        lines.append(_data_rows(data))
        lines.append("};")
        lines.append(f"static const crux_web_header_t crux_web_asset_headers_{index:04d}[] = {{")
        lines.append(f'    {{"Content-Type", "{content_type(path)}"}},')
        if gzip:
            lines.append('    {"Content-Encoding", "gzip"},')
        lines.append(f'    {{"Cache-Control", "{cache_value(path)}"}},')
        lines.append("    CRUX_WEB_ASSETS_SECURITY_HEADERS,")
        lines.append("};")
        lines.append("")
    lines.append("const crux_web_asset_t crux_web_asset_table[] = {")
    for index, (path, _) in enumerate(assets):
        count = 2 + (1 if gzip_flags[index] else 0) + SECURITY_HEADER_COUNT
        lines.append(f'    {{"{path}", crux_web_asset_data_{index:04d}, '
                     f"sizeof(crux_web_asset_data_{index:04d}), crux_web_asset_headers_{index:04d}, "
                     f"{count}u}},")
    lines.append("};")
    lines.append(f"const size_t crux_web_asset_count = {len(assets)}u;")
    lines.append("")
    routes = [(path, index) for index, (path, _) in enumerate(assets)]
    routes.extend(("/", index) for index, (path, _) in enumerate(assets) if path == "/index.html")
    routes.sort()
    for number, (path, index) in enumerate(routes):
        lines.append(f'CRUX_WEB_ROUTE(crux_web_asset_route_{number:04d}, "{path}", CRUX_WEB_GET, '
                     f"CRUX_WEB_PUBLIC, crux_web_assets_serve, &crux_web_asset_table[{index}]);")
    return "\n".join(lines) + "\n", len(routes)


def check_source(text):
    """Raise FormError unless text is exactly what render_source() writes."""
    style = _STYLE.search(text)
    if style is None:
        raise FormError("no style define")
    assets = []
    for found in _ASSET.finditer(text):
        path = found.group(1)
        if len(path) > PATH_MAX or not _PATH.match(path):
            raise FormError(f"{path!r} is not a path that the packager writes")
        suffix = path[path.rfind("."):].lower() if "." in path.rsplit("/", 1)[-1] else ""
        if suffix not in TYPES:
            raise FormError(f"{path!r} has no type that the packager serves")
        assets.append((path, bytes(int(token, 16) for token in _BYTE.findall(found.group(2)))))
    paths = [path for path, _ in assets]
    if not assets or paths != sorted(set(paths)) or "/index.html" not in paths:
        raise FormError("the assets are missing, repeated, out of order, or hold no /index.html")
    expected, _ = render_source("inline" if style.group(1) == "1" else "strict", assets)
    if text != expected:
        position = next((n for n, (a, b) in enumerate(zip(text, expected)) if a != b),
                        min(len(text), len(expected)))
        raise FormError(f"line {text.count(chr(10), 0, position) + 1} differs from what the packager "
                        "writes for these assets")
