"""Synthetic stock Zephyr checkout, patches, patched copy and frozen record for the bench freeze tests (design B2).

Everything lives in a temporary directory and is built with the real ``git``, ``tar`` and ``patch`` programs, the way
scripts/prepare-wolf-tls-zephyr.sh builds the real copy (``git archive | tar -x``, ``patch --strip=1
--no-backup-if-mismatch --quiet``, then the marker). The patches are NOT the wolfSSL patch and NOT the second (``tcp_init_isn``)
patch of session C11: they are synthetic text diffs of synthetic files, generated by git from two edit sets.
"""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'target'))
import patched_zephyr
import zephyr_tree

MARKER_FILE = '.crux-wolf-tls'
GIT_ENV = dict(os.environ, GIT_CONFIG_GLOBAL='/dev/null', GIT_CONFIG_SYSTEM='/dev/null', GIT_AUTHOR_NAME='t', GIT_AUTHOR_EMAIL='t@example.invalid',
               GIT_COMMITTER_NAME='t', GIT_COMMITTER_EMAIL='t@example.invalid')

KEEP, OMIT = object(), object()
STOCK = {
    'subsys/a.c': b'a1\na2\na3\na4\na5\n',
    'subsys/b.c': b'b1\nb2\nb3\n',
    'subsys/removed.c': b'gone soon\n',
    'include/x.h': b'#define X 1\n',
    'scripts/run.sh': (b'#!/bin/sh\necho run\n', 0o755),
    'doc/readme.rst': b'documents are not archived\n',
    'samples/s.c': b'samples are not archived\n',
    'tests/t.c': b'tests are not archived\n',
}


def available():
    """The real programs that the fixtures need."""
    return all(shutil.which(tool) for tool in ('git', 'tar', 'patch'))


def run(command, cwd=None, data=None, env=None):
    done = subprocess.run(command, cwd=cwd, input=data, capture_output=True, env=env or GIT_ENV)
    if done.returncode:
        raise AssertionError('%r failed: %s' % (command, done.stderr.decode(errors='replace')))
    return done.stdout


def write_tree(root, files):
    for relative, spec in files.items():
        data, mode = spec if isinstance(spec, tuple) else (spec, 0o644)
        path = Path(root) / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        os.chmod(path, mode)
    link = Path(root) / 'include' / 'link.h'
    if not link.is_symlink():
        os.symlink('x.h', link)


def git_repo(path, files):
    path.mkdir(parents=True)
    run(['git', 'init', '-q', '-b', 'main'], cwd=path)
    write_tree(path, files)
    run(['git', 'add', '-A'], cwd=path)
    run(['git', '-c', 'commit.gpgsign=false', 'commit', '-q', '-m', 'stock'], cwd=path)
    return run(['git', 'rev-parse', 'HEAD'], cwd=path).decode().strip()


# Edit sets of the two synthetic patches. Patch one modifies a.c, adds new.c and deletes removed.c. Patch two modifies a.c
# again (a second hunk), modifies b.c and modifies new.c, so a.c and new.c are each touched by both patches and the second
# patch does not apply to the stock tree. The independent variant touches disjoint files, so either order applies.
def edits_one(files, delete=False):
    files = dict(files)
    files['subsys/a.c'] = b'a1\na2 patched by one\na3\na4\na5\n'
    files['subsys/new.c'] = b'new file\nof patch one\n'
    if delete:
        del files['subsys/removed.c']
    return files


def edits_two(files):
    files = dict(files)
    files['subsys/a.c'] = files['subsys/a.c'].replace(b'a5\n', b'a5 patched by two\n')
    files['subsys/b.c'] = b'b1\nb2 patched by two\nb3\n'
    files['subsys/new.c'] = files['subsys/new.c'] + b'and of patch two\n'
    return files


def edits_two_independent(files):
    files = dict(files)
    files['subsys/b.c'] = b'b1\nb2 patched by two\nb3\n'
    return files


def patch_deletes():
    """Whether the local ``patch`` removes a file that a git diff deletes. GNU patch does; Apple's BSD patch leaves an empty file,
    which would make a copy differ from its own re-derivation for a reason that has nothing to do with the freeze."""
    import tempfile
    with tempfile.TemporaryDirectory() as temp:
        repo = Path(temp) / 'r'
        git_repo(repo, dict(STOCK))
        (repo / 'subsys' / 'removed.c').unlink()
        run(['git', 'add', '-A'], cwd=repo)
        text = run(['git', 'diff', '--cached', '--no-color', '--no-ext-diff'], cwd=repo)
        target = Path(temp) / 't'
        (target / 'subsys').mkdir(parents=True)
        (target / 'subsys' / 'removed.c').write_bytes(STOCK['subsys/removed.c'])
        run(['patch', '--strip=1', '--no-backup-if-mismatch', '--quiet'], cwd=target, data=text)
        return not (target / 'subsys' / 'removed.c').exists()


def make_patches(root, independent=False, delete=False):
    """Two patch files as git writes them from the edit sets, named and ordered as the declaration would list them."""
    repo = Path(root) / 'generator'
    git_repo(repo, STOCK)
    texts = []
    for edit in (lambda files: edits_one(files, delete), edits_two_independent if independent else edits_two):
        current = {p.relative_to(repo).as_posix(): p.read_bytes() for p in repo.rglob('*')
                   if p.is_file() and '.git' not in p.relative_to(repo).parts and not p.is_symlink()}
        wanted = edit(current)
        for relative in set(current) - set(wanted):
            (repo / relative).unlink()
        for relative, data in wanted.items():
            target = repo / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        run(['git', 'add', '-A'], cwd=repo)
        texts.append(run(['git', 'diff', '--cached', '--no-color', '--no-ext-diff', '--no-renames'], cwd=repo))
        run(['git', '-c', 'commit.gpgsign=false', 'commit', '-q', '-m', 'edit'], cwd=repo)
    return texts


def archive(zephyr, pin, destination):
    destination.mkdir(parents=True)
    data = run(['git', '-C', str(zephyr), 'archive', pin, ':!doc', ':!samples', ':!tests'])
    run(['tar', '-x', '-C', str(destination)], data=data)


def apply_patch(copy, patch_path):
    run(['patch', '--strip=1', '--no-backup-if-mismatch', '--quiet'], cwd=copy, data=Path(patch_path).read_bytes())
    leftovers = [p for p in Path(copy).rglob('*') if p.name.endswith(('.rej', '.orig'))]
    assert not leftovers, leftovers


class Bench:
    """A complete synthetic bench build tree: stock checkout, patches, copy, declared block, manifest, pre-build capture."""

    def __init__(self, root, count=2, independent=False, names=None, delete=False):
        self.root = Path(root)
        self.count = count
        self.names = names or ['first-%d.patch' % i for i in range(1, count + 1)]
        self.stock = self.root / 'ws' / 'zephyr'
        self.pin = git_repo(self.stock, STOCK)
        self.patches = self.root / 'patches'
        self.patches.mkdir()
        for name, text in zip(self.names, make_patches(self.root, independent, delete)):
            (self.patches / name).write_bytes(text)
        self.copy = self.root / 'ws' / 'zephyr-wolf'
        self.build = self.root / 'repo' / 'build' / 'bench'
        self.build.mkdir(parents=True)
        self.out_number = 0
        self.rebuild_copy()
        self.write_compile_commands()
        self.workspace = self.root / 'ws'
        self.write_inputs()
        self.block = self.declare()
        self.write_manifest()
        self.recapture()

    # copy ---------------------------------------------------------------------------------------------------------
    def rebuild_copy(self, names=None, marker_names=None):
        """Make the copy as the prepare script does: archive, apply the named patches in order, write the marker."""
        shutil.rmtree(self.copy, ignore_errors=True)
        archive(self.stock, self.pin, self.copy)
        names = list(self.names if names is None else names)
        for name in names:
            apply_patch(self.copy, self.patches / name)
        marker = marker_names if marker_names is not None else names
        hashes = [hashlib.sha256((self.patches / n).read_bytes()).hexdigest() for n in marker]
        (self.copy / MARKER_FILE).write_text('%s %s\n' % (self.pin, ' '.join(hashes)))

    def write_compile_commands(self, files=None):
        build = str(self.root / 'repo' / 'build' / 'bench' / 'cc')
        files = files if files is not None else [str(self.copy / 'subsys' / 'a.c'), str(self.copy / 'include' / 'x.h'),
                                                 str(self.root / 'repo' / 'src' / 'main.c')]
        entries = [dict(directory=build, command='cc -c ' + f, file=f) for f in files]
        self.compile_commands = self.build / 'compile_commands.json'
        self.compile_commands.write_text(json.dumps(entries))

    def write_inputs(self, projects=None):
        """The inputs file of ``record-build-provenance.py --capture-inputs`` (west projects only): the stock checkout is the west
        ``zephyr`` project at ``ws/zephyr``, and the copy is not a project."""
        if projects is None:
            projects = [dict(name='zephyr', path='zephyr', revision=self.pin, git_commit=self.pin, dirty=False)]
        self.inputs = self.build / 'inputs.json'
        self.inputs.write_text(json.dumps(dict(west_projects=projects)))

    # declaration ---------------------------------------------------------------------------------------------------
    def declare(self):
        """The block the declaration would hold, derived here from the files themselves (hashlib, not the module under test)."""
        patches = [dict(name=n, sha256=hashlib.sha256((self.patches / n).read_bytes()).hexdigest()) for n in self.names]
        parsed = [(n, zephyr_tree.patch_touched_files((self.patches / n).read_bytes())) for n in self.names]
        files = []
        for item in zephyr_tree.net_changes(parsed):
            target = self.copy / item['path']
            files.append(dict(path=item['path'], change=item['change'],
                              sha256=hashlib.sha256(target.read_bytes()).hexdigest() if item['change'] != 'deleted' else None,
                              patches=item['patches']))
        digest = zephyr_tree.tree_digest(self.copy)
        return dict(schema=2, decision='D8', marker_file=MARKER_FILE, pin=self.pin, patches=patches, patched_files=files,
                    tree=dict(algorithm=zephyr_tree.ALGORITHM, sha256=digest['sha256'], file_count=digest['file_count']))

    def write_manifest(self, block=KEEP, extra=None):
        """The bench manifest. ``block`` defaults to the declared block, ``None`` writes a null, ``OMIT`` leaves the key out."""
        manifest = dict(image_id='crux-mgmt-bench-rt1060-evkb-b')
        if block is not OMIT:
            manifest['patched_zephyr'] = self.block if block is KEEP else block
        manifest.update(extra or {})
        self.manifest = self.build / 'bench-manifest.json'
        self.manifest.write_text(json.dumps(manifest, indent=2, sort_keys=True) + '\n')

    def recapture(self):
        self.pre = self.build / 'pre.json'
        if self.pre.exists():
            self.pre.unlink()
        patched_zephyr.capture(self.copy, self.pre, MARKER_FILE)

    # freeze --------------------------------------------------------------------------------------------------------
    def out(self):
        self.out_number += 1
        return self.build / ('patched-zephyr' if self.out_number == 1 else 'patched-zephyr-%d' % self.out_number)

    def freeze(self, **override):
        arguments = dict(copy=self.copy, zephyr=self.stock, patches=self.patches, manifest=self.manifest,
                         compile_commands=self.compile_commands, pre=self.pre, out=self.out(), inputs=self.inputs,
                         workspace=self.workspace)
        arguments.update(override)
        return patched_zephyr.freeze(**arguments)

    def frozen(self):
        """Freeze and return the record path of the frozen folder."""
        out = self.out()
        self.freeze(out=out)
        return out / 'patched-zephyr.json'
