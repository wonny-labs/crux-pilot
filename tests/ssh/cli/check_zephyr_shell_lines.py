#!/usr/bin/env python3
"""Keep zephyr_shell_lines.h equal to what the pinned Zephyr registers.

The tests of Issue #193 run these lines on the SSH entry points, and each must be an unknown command. The
list is generated, so that a command of the shell is not missed by memory: every root command registered
under Zephyr's own directories, and each subcommand of `kernel`, including `kernel thread`, with some lines
that show the shell's own syntax. Modules outside the Zephyr tree are not scanned. With --write it updates the
header. Without it, it fails if the header differs, so that a Zephyr upgrade has to bring the list along.

The scan is lexical. A command behind a macro of another name is missed, which is why the entry points'
symbol check and the image check of the shell rule do not depend on this list.
"""
import argparse
from pathlib import Path
import re
import sys

HEADER = Path(__file__).with_name("zephyr_shell_lines.h")
SCANNED = ("subsys", "drivers", "kernel", "lib", "arch", "soc")
ROOT = re.compile(r"\bSHELL_(COND_)?CMD(?:_ARG)?_REGISTER\(\s*([^,\s]+)\s*,\s*([^,\s]+)")
KERNEL = re.compile(r"\bKERNEL_(THREAD_)?CMD(?:_ARG)?_ADD\(\s*([^,\s]+)\s*,")
NAME = re.compile(r"[a-z][\w-]*$")
# Crux has its own help, so the name exists here. Its answer to these arguments is in EXTRA.
NOT_LISTED = {"help"}
EXTRA = (
    "device list", "devmem 0x0", "shell colors", "shell colors off", "shell echo off", "shell stats",
    "resize default", "select kernel", "date get", "log status", "net iface", "net ping 127.0.0.1",
    "gpio get", "i2c scan", "flash read", "fs ls /", "app version", "kernel reboot cold",
    "kernel reboot warm", "zyclictest start", "uart:~$", "help -h", "kernel -h", "shell -h",
)
# What the scan must find, so that it cannot pass having read nothing.
EXPECTED = {"kernel", "shell", "rem", "app", "zyclictest", "kernel thread", "kernel thread list", "kernel uptime"}


def scan(zephyr):
    lines = set()
    for directory in SCANNED:
        for path in sorted((zephyr / directory).rglob("*.c")):
            text = path.read_text(encoding="utf-8", errors="replace")
            for match in ROOT.finditer(text):
                name = match.group(3) if match.group(1) else match.group(2)
                if NAME.match(name) and name not in NOT_LISTED:
                    lines.add(name)
    for path in sorted((zephyr / "subsys/shell/modules/kernel_service").rglob("*.c")):
        for match in KERNEL.finditer(path.read_text(encoding="utf-8", errors="replace")):
            lines.add(f"kernel thread {match.group(2)}" if match.group(1) else f"kernel {match.group(2)}")
    return lines


def render(lines):
    body = "".join(f'    "{line}",\n' for line in sorted(lines))
    return ("/* Generated by check_zephyr_shell_lines.py from the pinned Zephyr. Do not edit. */\n"
            "/* clang-format off */\n"
            "static const char *const zephyr_shell_lines[] = {\n" + body + "};\n"
            "/* clang-format on */\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--zephyr", type=Path, required=True)
    parser.add_argument("--write", action="store_true")
    arguments = parser.parse_args()
    lines = scan(arguments.zephyr)
    missing = EXPECTED - lines
    if missing:
        print(f"The scan did not find {sorted(missing)}, so it cannot be trusted.", file=sys.stderr)
        return 1
    text = render(lines | set(EXTRA))
    if arguments.write:
        HEADER.write_text(text, encoding="utf-8")
        return 0
    if HEADER.read_text(encoding="utf-8") != text:
        print(f"{HEADER.name} differs from this Zephyr. Run this script with --write.", file=sys.stderr)
        return 1
    print(f"{HEADER.name} holds what this Zephyr registers: {len(lines | set(EXTRA))} lines.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
